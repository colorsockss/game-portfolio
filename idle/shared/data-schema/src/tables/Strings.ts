export interface StringsRow {
  // 인덱스 0: 문장 키. 앞부분이 쓰는 곳이다(화면·위젯 이름, 테이블은 item·stage·monster·skill·hero·tutorial). 코드와 테이블의 키 열(ref Strings)이 이 키를 쓴다
  "id": StringsId;
  // 인덱스 1: 한국어. 기본 언어라서 기기 언어가 없는 언어이면 이것을 보인다. 언어 열은 ISO 639-1 이름이고 모든 줄을 채운다. {이름}은 코드가 넘기는 인자다
  "ko": string;
  // 인덱스 2: 영어. 한국어와 같은 {이름} 인자를 쓴다
  "en": string;
}

export async function deserializeStringsMessagePack(bytes: Uint8Array | ArrayBuffer): Promise<Map<StringsId, StringsRow>> {
  const result = new Map<StringsId, StringsRow>();
  for (const row of readMessagePack(bytes)) {
    const record: StringsRow = {
      "id": row[0] as StringsId,
      "ko": row[1] as string,
      "en": row[2] as string,
    };
    result.set(record.id, record);
  }
  return result;
}
